import type { LocalizedText, ScenarioLesson } from "@/types/course";

const lt = (zh: string, en: string): LocalizedText => ({ zh, en });

type PhraseInput = {
  dutch: string;
  zh: string;
  en: string;
};

type DialogueInput = {
  speaker: string;
  dutch: string;
  zh: string;
  en: string;
};

type ScenarioInput = {
  id: string;
  level: ScenarioLesson["level"];
  stage: ScenarioLesson["stage"];
  titleZh: string;
  titleEn: string;
  scenarioZh: string;
  scenarioEn: string;
  goals: Array<{ zh: string; en: string }>;
  words: string[];
  phrases: PhraseInput[];
  dialogue: DialogueInput[];
  speakingPromptZh: string;
  speakingPromptEn: string;
  speakingDutch: string;
  speakingMeaningZh: string;
  speakingMeaningEn: string;
  writingPromptZh?: string;
  writingPromptEn?: string;
  writingDutch?: string;
  writingMeaningZh?: string;
  writingMeaningEn?: string;
  checklist: Array<{ zh: string; en: string }>;
  sounds?: string[];
  grammar?: string[];
};

const phrase = (dutch: string, zh: string, en: string): PhraseInput => ({ dutch, zh, en });
const line = (speaker: string, dutch: string, zh: string, en: string): DialogueInput => ({ speaker, dutch, zh, en });

const scenario = (input: ScenarioInput): ScenarioLesson => ({
  id: input.id,
  level: input.level,
  stage: input.stage,
  title: lt(input.titleZh, input.titleEn),
  scenario: lt(input.scenarioZh, input.scenarioEn),
  learningGoals: input.goals.map((goal) => lt(goal.zh, goal.en)),
  usefulWords: input.words,
  usefulPhrases: input.phrases.map((item) => ({
    dutch: item.dutch,
    meaning: lt(item.zh, item.en),
  })),
  dialogue: input.dialogue.map((item) => ({
    speaker: item.speaker,
    dutch: item.dutch,
    meaning: lt(item.zh, item.en),
  })),
  speakingTask: {
    prompt: lt(input.speakingPromptZh, input.speakingPromptEn),
    usefulPhrases: input.phrases.map((item) => item.dutch),
    sampleAnswer: {
      dutch: input.speakingDutch,
      meaning: lt(input.speakingMeaningZh, input.speakingMeaningEn),
    },
  },
  writingTask:
    input.writingDutch && input.writingPromptZh && input.writingPromptEn
      ? {
          prompt: lt(input.writingPromptZh, input.writingPromptEn),
          requiredInfo: [lt("称呼或开场", "Greeting/opening"), lt("主要信息", "Main message"), lt("结尾或下一步", "Closing/next step")],
          sampleAnswer: {
            dutch: input.writingDutch,
            meaning: lt(input.writingMeaningZh ?? "参考写作答案", input.writingMeaningEn ?? "Sample writing answer"),
          },
        }
      : undefined,
  checklist: input.checklist.map((item) => lt(item.zh, item.en)),
  relatedSoundLessonIds: input.sounds ?? ["sound-ei-ij", "sound-oe"],
  relatedSmartWordIds: input.words.map((word) => `word-${word.toLowerCase().replace(/\s+/g, "-")}`),
  relatedGrammarRuleIds: input.grammar ?? ["grammar-a1-v2"],
});

